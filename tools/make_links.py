"""Generate personal links, the relay's token hashes, and the site's config.js.

Usage:
  python3 tools/make_links.py --site https://YOU.github.io/winterhouse-survey/ \
                              --endpoint https://winterhouse-survey.YOU.workers.dev \
                              [--album https://link-to-shared-video-folder]

Writes:
  docs/config.js                  public: names, host, prediction assignments, endpoint
  private/links.csv               PRIVATE: each person's two links (send by DM)
  private/worker_TOKENS.json      PRIVATE: paste as the Worker's TOKENS secret
Re-running keeps existing codes (stored in private/codes.json) unless --new-codes.
"""
import argparse, csv, hashlib, json, os, secrets, sys
from urllib.parse import urlencode

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import prediction_design as pdz  # noqa: E402

HOST = "Ryan"

ap = argparse.ArgumentParser()
ap.add_argument("--site", required=True)
ap.add_argument("--endpoint", required=True)
ap.add_argument("--album", default="")
ap.add_argument("--new-codes", action="store_true")
a = ap.parse_args()

priv = os.path.join(ROOT, "private")
os.makedirs(priv, exist_ok=True)
codes_path = os.path.join(priv, "codes.json")
codes = {}
if os.path.exists(codes_path) and not a.new_codes:
    codes = json.load(open(codes_path))
for n in pdz.NAMES:
    codes.setdefault(n, secrets.token_urlsafe(9))
json.dump(codes, open(codes_path, "w"), indent=1)

hashes = {n: hashlib.sha256(codes[n].encode()).hexdigest() for n in pdz.NAMES}
json.dump(hashes, open(os.path.join(priv, "worker_TOKENS.json"), "w"))

site = a.site if a.site.endswith("/") else a.site + "/"
with open(os.path.join(priv, "links.csv"), "w", newline="") as f:
    w = csv.writer(f)
    w.writerow(["name", "part1_link", "part2_link"])
    for n in pdz.NAMES:
        w.writerow([n] + [site + "?" + urlencode({"me": n, "k": codes[n], "part": p}) for p in (1, 2)])

cfg = {
    "endpoint": a.endpoint.rstrip("/"),
    "host": HOST,
    "names": pdz.NAMES,
    "albumLink": a.album,
    "prediction": pdz.by_predictor(pdz.build()),
}
with open(os.path.join(ROOT, "docs", "config.js"), "w") as f:
    f.write("// Generated by tools/make_links.py. Safe to publish: holds no codes.\n")
    f.write("window.SURVEY_CONFIG = " + json.dumps(cfg, indent=1) + ";\n")
print("Wrote docs/config.js, private/links.csv, private/worker_TOKENS.json")
